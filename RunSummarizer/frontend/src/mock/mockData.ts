/**
 * Helper to build realistic laps with speed, duration, and heart rate telemetry.
 */
function createLaps(specs: Array<{ distKm: number; paceSecs: number; hr: number; type: LapType }>) {
  return specs.map((spec, i) => {
    const distMeters = Math.round(spec.distKm * 1000);
    const durationSecs = Math.round(spec.distKm * spec.paceSecs);
    const speedMs = Number((distMeters / durationSecs).toFixed(2));
    const typeDisplay = spec.type === LapType.RUN ? 'Run' : spec.type === LapType.RECOVERY ? 'Recovery' : 'Rest';

    return {
      lapIndex: i,
      typeId: spec.type,
      typeName: typeDisplay.toLowerCase(),
      typeDisplay,
      distance: distMeters,
      duration: durationSecs,
      speed: speedMs,
      avgHr: spec.hr,
      maxHr: spec.hr + Math.floor(Math.random() * 6) + 4,
      elevationGain: Math.floor(Math.random() * 8) + 2,
      version: 0,
    };
  });
}

